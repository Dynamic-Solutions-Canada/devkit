import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import test from 'node:test'
import { fileURLToPath } from 'node:url'

import {
  evaluateEdit,
  isInGeneratedDirectory,
  loadConfig,
} from '../templates/generated-file-guard.mjs'

// Ported from persistent's scripts/hooks/generated-file-guard.test.ts, the best copy (KIT-10).

const guard = fileURLToPath(
  new URL('../templates/generated-file-guard.mjs', import.meta.url),
)
const config = {
  generatedDirectories: ['apps/mobile/android'],
  checkHeaders: true,
}

/** A temporary repo root, removed after the test. */
function repo(t) {
  const root = mkdtempSync(path.join(os.tmpdir(), 'generated-file-guard-'))
  t.after(() => rmSync(root, { recursive: true, force: true }))
  return root
}

/** A PreToolUse event for one edit tool and target. */
function editEvent(cwd, toolName, target) {
  const field = toolName === 'NotebookEdit' ? 'notebook_path' : 'file_path'
  return {
    hook_event_name: 'PreToolUse',
    tool_name: toolName,
    cwd,
    tool_input: { [field]: target },
  }
}

test('files with a generated header are denied while ordinary source stays editable', (t) => {
  const root = repo(t)
  writeFileSync(
    path.join(root, 'generated.ts'),
    '/** GENERATED FILE - DO NOT EDIT. */\nexport const value = 1\n',
  )
  writeFileSync(path.join(root, 'source.ts'), 'export const value = 1\n')

  const denied = evaluateEdit(
    editEvent(root, 'Edit', 'generated.ts'),
    config,
    root,
  )
  assert.equal(denied?.hookSpecificOutput.permissionDecision, 'deny')
  assert.match(
    denied?.hookSpecificOutput.permissionDecisionReason,
    /generated\.ts/,
  )
  assert.equal(
    evaluateEdit(editEvent(root, 'Edit', 'source.ts'), config, root),
    null,
  )
})

test("devkit's own generated files are protected by their header", (t) => {
  const root = repo(t)
  for (const template of ['run-dev.mjs', 'deploy-over-ssh.mjs']) {
    const source = fileURLToPath(
      new URL(`../templates/${template}`, import.meta.url),
    )
    const denied = evaluateEdit(editEvent(root, 'Edit', source), config, root)
    assert.equal(
      denied?.hookSpecificOutput.permissionDecision,
      'deny',
      template,
    )
  }
})

test('every configured generated directory is denied, header or not, for each edit tool', (t) => {
  const root = repo(t)
  mkdirSync(path.join(root, 'apps', 'mobile', 'android', 'app'), {
    recursive: true,
  })
  const target = path.join(
    root,
    'apps',
    'mobile',
    'android',
    'app',
    'MainActivity.java',
  )

  for (const tool of ['Edit', 'MultiEdit', 'Write', 'NotebookEdit']) {
    const denied = evaluateEdit(editEvent(root, tool, target), config, root)
    assert.equal(denied?.hookSpecificOutput.permissionDecision, 'deny', tool)
    assert.match(
      denied?.hookSpecificOutput.permissionDecisionReason,
      /apps\/mobile\/android/,
    )
  }
})

test('a sibling whose name only starts like a generated directory is not matched', () => {
  const root = '/repo'
  assert.equal(
    isInGeneratedDirectory(
      '/repo/apps/mobile/android/app/A.java',
      ['apps/mobile/android'],
      root,
    ),
    true,
  )
  assert.equal(
    isInGeneratedDirectory(
      '/repo/apps/mobile/android-plugin/A.java',
      ['apps/mobile/android'],
      root,
    ),
    false,
  )
  assert.equal(
    isInGeneratedDirectory(
      '/repo/apps/mobile/android-plugin/A.java',
      ['apps/mobile/android/'],
      root,
    ),
    false,
  )
})

test('non-edit tools, other events and new files are left alone', (t) => {
  const root = repo(t)
  const bash = {
    hook_event_name: 'PreToolUse',
    tool_name: 'Bash',
    cwd: root,
    tool_input: { command: 'ls' },
  }
  assert.equal(evaluateEdit(bash, config, root), null)
  assert.equal(
    evaluateEdit(
      { ...editEvent(root, 'Edit', 'x.ts'), hook_event_name: 'PostToolUse' },
      config,
      root,
    ),
    null,
  )
  assert.equal(
    evaluateEdit(editEvent(root, 'Write', 'new-file.ts'), config, root),
    null,
  )
})

test('the header check can be turned off, and a missing config means defaults', (t) => {
  const root = repo(t)
  writeFileSync(
    path.join(root, 'generated.ts'),
    '// generated by tool, do not edit\n',
  )
  assert.equal(
    evaluateEdit(
      editEvent(root, 'Edit', 'generated.ts'),
      { generatedDirectories: [], checkHeaders: false },
      root,
    ),
    null,
  )
  assert.deepEqual(loadConfig(path.join(root, 'missing.json')), {
    generatedDirectories: [],
    checkHeaders: true,
  })
})

test('the hook answers on stdout, and a broken event lets the edit proceed with a message', () => {
  const event = JSON.stringify({
    hook_event_name: 'PreToolUse',
    tool_name: 'Edit',
    tool_input: { file_path: guard },
  })
  const denied = spawnSync(process.execPath, [guard], {
    input: event,
    encoding: 'utf8',
  })
  assert.equal(denied.status, 0)
  assert.equal(
    JSON.parse(denied.stdout).hookSpecificOutput.permissionDecision,
    'deny',
  )

  const broken = spawnSync(process.execPath, [guard], {
    input: 'not json',
    encoding: 'utf8',
  })
  assert.equal(broken.status, 0)
  assert.match(JSON.parse(broken.stdout).systemMessage, /guard failed/)
})
